"""The app's routes match a committed list (tests/route_manifest.txt).

Why: a truncated file, a bad merge or a blueprint that failed to register
drops routes without failing a single other test -- the page just starts
getting 404s. This pins every rule + its methods.

When you add, remove or rename a route ON PURPOSE, regenerate the list and
commit it with the change:

    python tests/test_route_manifest.py --write

(After merging branches that each added routes, regenerate once on the merged
tree.)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = Path(__file__).resolve().parent / "route_manifest.txt"


def current_routes() -> list:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    import app as app_mod
    lines = set()
    for rule in app_mod.app.url_map.iter_rules():
        methods = ",".join(sorted(rule.methods - {"HEAD", "OPTIONS"})) or "OPTIONS"
        lines.add(f"{rule.rule} {methods}")
    return sorted(lines)


def test_routes_match_the_committed_manifest():
    want = [ln for ln in MANIFEST.read_text().splitlines()
            if ln.strip() and not ln.startswith("#")]
    got = current_routes()
    missing = sorted(set(want) - set(got))
    extra = sorted(set(got) - set(want))
    assert not missing and not extra, (
        "routes changed.\n  gone from the app: %s\n  new in the app: %s\n"
        "If intended: python tests/test_route_manifest.py --write"
        % (missing or "-", extra or "-"))


if __name__ == "__main__":
    if "--write" in sys.argv:
        rows = current_routes()
        MANIFEST.write_text(
            "# Generated by: python tests/test_route_manifest.py --write\n"
            "# One line per route: <rule> <METHODS>. Do not edit by hand.\n"
            + "\n".join(rows) + "\n")
        print(f"wrote {len(rows)} routes to {MANIFEST}")
    else:
        print("\n".join(current_routes()))
